package org.example.class5;

public class E5NestedLoops {
    public static void main(String[] args) {

        // A

        for (int i = 0; i < 20; i++) {

            for (int j = 0; j < 10; j++) {
                System.out.print("*");
            }
            System.out.println();

        }


    }

}
