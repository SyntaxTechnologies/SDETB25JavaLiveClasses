package org.example.class5;

public class E6NestedLoops {
    public static void main(String[] args) {

        // A

        for (int i = 0; i < 5; i++) {

            for (int j = 0; j < 8; j++) {
                System.out.print(i);
            }
            System.out.println();
        }


    }

}
