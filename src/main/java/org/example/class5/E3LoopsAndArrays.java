package org.example.class5;

public class E3LoopsAndArrays {
    public static void main(String[] args) {
        int[] numbers = {10, 20, 30, 45, 66, 12, 88, 95, 1, 5, 1, 4};

        for (int i = 0; i < numbers.length; i++) {

            if(numbers[i]==12) {
                System.out.println("Number 12 found");

            }
        }

    }

}
